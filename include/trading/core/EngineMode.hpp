#pragma once

// ============================================================
// EngineMode
// ============================================================
//
// 交易系统运行模式定义。
//
// CMETradingSystem 需要支持三种运行环境：
//
// BACKTEST
//     历史行情回放和策略验证。
//
// PAPER
//     模拟交易环境，不连接真实交易账户。
//
// LIVE
//     实盘交易环境，连接真实行情和交易接口。
//
// 三种模式共享同一套 Engine 架构，区别主要在于：
// - 数据来源不同
// - 订单执行方式不同
// - 风险控制要求不同
//
// ============================================================

namespace CMETradingSystem::Core {

enum class EngineMode
{
    // 历史数据回测模式
    BACKTEST,

    // 模拟交易模式
    PAPER,

    // 实盘交易模式
    LIVE
};

}
