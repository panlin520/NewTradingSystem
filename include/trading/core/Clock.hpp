#pragma once

#include <cstdint>

namespace CMETradingSystem::Core {

// ============================================================
// Clock
// ============================================================
//
// Clock 是交易系统中的时间抽象层。
//
// 为什么需要 Clock？
//
// 高频交易系统不能到处直接调用系统时间函数。
// 统一时间接口可以支持：
//
// - 实盘模式：读取真实交易时间
// - 回测模式：读取历史数据时间
// - 模拟模式：控制模拟时间推进
//
// 未来流程：
//
// Backtest:
//     Historical Event
//            |
//            v
//          Clock
//
// Live:
//     Exchange Timestamp
//            |
//            v
//          Clock
//
// 这样策略和引擎不需要关心时间来源。
//
// ============================================================

class Clock
{
public:

    // 获取当前系统时间。
    //
    // 返回：
    // uint64_t 时间戳
    //
    // 高频交易通常使用纳秒级时间。
    uint64_t now() const;
};

}
