#pragma once

namespace CMETradingSystem::Core {

// ============================================================
// State
// ============================================================
//
// State 保存交易系统当前运行状态。
//
// 简单理解：
//
// Engine 是控制中心，State 是它记录的运行状态。
//
// 例如：
//
// 程序启动：
//     running = false
//
// Engine.start():
//     running = true
//
// Engine.stop():
//     running = false
//
// 后续这里可以扩展：
// - 当前交易模式
// - 系统健康状态
// - 风控状态
// - 数据连接状态
//
// State 不负责业务计算，只保存状态。
//
// ============================================================

struct State
{
    // 表示交易系统是否正在运行。
    bool running{false};
};

}
