#include "trading/core/Engine.hpp"

namespace CMETradingSystem::Core {

// ============================================================
// Engine 构造函数
//
// 作用：创建交易系统运行引擎。
//
// 当前阶段：
//     只保存运行模式(BACKTEST/PAPER/LIVE)。
//
// 后续完整交易系统中：
//     Engine 会负责协调：
//
//          MarketData
//              |
//              v
//          EventBus
//              |
//              v
//          Dispatcher
//              |
//              +---- OrderBook
//              +---- Strategy
//              +---- Risk
//              +---- Execution
//
// 注意：
//     Engine 本身不负责行情解析、不负责策略计算。
//     它只是整个系统的运行控制中心。
// ============================================================
Engine::Engine(EngineMode mode)
    : mode_(mode)
{
}


// ============================================================
// start()
//
// 启动交易系统。
//
// 当前实现：
//     只修改内部状态：running = true
//
// 未来扩展：
//     1. 启动数据源
//     2. 启动事件循环
//     3. 启动策略模块
//     4. 开始处理市场事件
// ============================================================
void Engine::start()
{
    state_.running = true;
}


// ============================================================
// stop()
//
// 停止交易系统。
//
// 未来扩展：
//     1. 停止接收行情
//     2. 保存系统状态
//     3. 安全关闭交易模块
// ============================================================
void Engine::stop()
{
    state_.running = false;
}


// ============================================================
// running()
//
// 查询当前 Engine 是否正在运行。
//
// 返回：
//     true  - 系统运行中
//     false - 系统已经停止
// ============================================================
bool Engine::running() const
{
    return state_.running;
}


// ============================================================
// mode()
//
// 获取当前交易模式。
//
// 三种模式：
//     BACKTEST - 历史数据回测
//     PAPER    - 模拟交易
//     LIVE     - 实盘交易
//
// 三种模式共享同一套 Engine 架构，
// 只是数据源和执行模块不同。
// ============================================================
EngineMode Engine::mode() const
{
    return mode_;
}

}
